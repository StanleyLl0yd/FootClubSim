import { isPlainJsonTree } from './plain-json-tree.js';
import { M1_CLOCK_END_SECONDS, M1_CLOCK_STEP_SECONDS } from './m1-clock.js';
import {
  simulateM1V8WithTimedSubstitutionCoverage,
  type M1V8TimedSubstitutionExecution,
} from './m1-v8-timed-substitution-coverage.js';

/**
 * A new research-only virtual referee admission, not a replacement for v8.
 * IFAB 2026/27 Law 8: a goal requires a subsequent kickoff. In v8, seeded
 * shot events occur at checkpoint-1, before the next command checkpoint.
 * Thus a goal is an engine-generated (rather than a client-claimed)
 * restart candidate. No other supposed stoppages are accepted here.
 */
export const M1_V9_GOAL_RESTART_SCHEMA_VERSION = 1 as const;
export const M1_V9_GOAL_RESTART_RULES_ID =
  'ifab-2026-27-law-8-goal-restart-research' as const;
const MAX_COMMANDS = 212;

export type M1V9GoalRestartError =
  | 'INVALID_COMMANDS' | 'MISSING_ENGINE_GOAL_RESTART'
  | 'UNSUPPORTED_HALF_TIME' | 'INVALID_ENGINE_TIMING'
  | 'TIMING_ADMISSION_REJECTED';

export type M1V9GoalRestartAdmission =
  | Readonly<{ ok: false; error: M1V9GoalRestartError;
    timingError?: string }>
  | Readonly<{
    ok: true;
    schemaVersion: typeof M1_V9_GOAL_RESTART_SCHEMA_VERSION;
    rulesId: typeof M1_V9_GOAL_RESTART_RULES_ID;
    status: 'ENGINE_DERIVED_GOAL_RESTART_NOT_FULL_VIRTUAL_REFEREE';
    /** Only goals generated by the same internally replayed v8 run. */
    restartEvidence: readonly Readonly<{
      shotEventId: string;
      goalRunningSeconds: number;
      candidateRestartRunningSeconds: number;
      scoringTeamId: string;
    }>[];
    acceptedStoppageGroups: number;
    normalSubstitutionCount: number;
    refereeOrigin: 'INTERNAL_V8_REPLAY';
    wallClockTimingAuthenticated: false;
    fullLaw8RestartProcedureVerified: false;
    result: Extract<M1V8TimedSubstitutionExecution, { ok: true }>['result'];
  }>;

const fail = (error: M1V9GoalRestartError,
  timingError?: string): M1V9GoalRestartAdmission =>
  timingError === undefined ? { ok: false, error } :
    { ok: false, error, timingError };
const record = (value: unknown): value is Record<string, unknown> =>
  value !== null && typeof value === 'object' && !Array.isArray(value);

/**
 * This new entrypoint uses the existing fully replayed v8 score generation
 * AND full single/group IFAB time-limited departure coverage. It refuses
 * client-admitted 'referee-authorized' substitutions at non-goal checkpoints.
 *
 * A goal at t=299 is a LAW-8 restart candidate at the next virtual t=300
 * checkpoint. This does NOT prove the ball was put into play precisely at
 * second 300, validate the ten-second wall clock, or cover fouls, throw-ins,
 * corners and referee discretionary stoppages.
 */
export function simulateM1V9GoalRestartSubstitutions(
  prematch: unknown, policy: unknown, plannedCommands: unknown,
  refereeDecisions: unknown, medicalActions: unknown,
  timedDepartureDossiers: unknown,
): M1V9GoalRestartAdmission {
  if (!isPlainJsonTree(plannedCommands) ||
      !Array.isArray(plannedCommands) ||
      plannedCommands.length > MAX_COMMANDS) return fail('INVALID_COMMANDS');
  const requested = new Set<number>();
  let normalSubstitutionCount = 0;
  for (const raw of plannedCommands) {
    if (!record(raw) || raw.kind !== 'substitute-normal') continue;
    if (!Number.isInteger(raw.elapsedSeconds) ||
        (raw.elapsedSeconds as number) < 0 ||
        (raw.elapsedSeconds as number) >= M1_CLOCK_END_SECONDS ||
        (raw.elapsedSeconds as number) % M1_CLOCK_STEP_SECONDS !== 0) {
      return fail('INVALID_COMMANDS');
    }
    if (raw.stoppage === 'half-time') return fail('UNSUPPORTED_HALF_TIME');
    if (raw.stoppage !== 'referee-authorized') return fail('INVALID_COMMANDS');
    requested.add(raw.elapsedSeconds as number);
    normalSubstitutionCount++;
  }
  // Calculates from source, not from any caller-supplied alleged goal list.
  const checked = simulateM1V8WithTimedSubstitutionCoverage(
    prematch, policy, plannedCommands, refereeDecisions,
    medicalActions, timedDepartureDossiers);
  if (!checked.ok) {
    return fail('TIMING_ADMISSION_REJECTED',
      checked.error === 'MATCH_REJECTED' ?
        checked.matchError : checked.error);
  }
  const restarts: Extract<M1V9GoalRestartAdmission, {ok:true}>['restartEvidence'][number][] = [];
  const permitted = new Set<number>();
  for (const event of checked.result.events) {
    if (event.type !== 'shot' || event.outcome !== 'goal') continue;
    const second = event.elapsedSeconds + 1;
    // The v8 shot is timestamped as the very end of a 300s phase;
    // a goal at full-time does not guarantee a later kickoff.
    if (second < M1_CLOCK_STEP_SECONDS ||
        second >= M1_CLOCK_END_SECONDS ||
        second % M1_CLOCK_STEP_SECONDS !== 0) {
      return fail('INVALID_ENGINE_TIMING');
    }
    if (permitted.has(second)) return fail('INVALID_ENGINE_TIMING');
    permitted.add(second);
    restarts.push({
      shotEventId: event.id,
      goalRunningSeconds: event.elapsedSeconds,
      candidateRestartRunningSeconds: second,
      scoringTeamId: event.teamId,
    });
  }
  for (const second of requested) {
    if (!permitted.has(second)) return fail('MISSING_ENGINE_GOAL_RESTART');
  }
  return {
    ok: true, schemaVersion: M1_V9_GOAL_RESTART_SCHEMA_VERSION,
    rulesId: M1_V9_GOAL_RESTART_RULES_ID,
    status: 'ENGINE_DERIVED_GOAL_RESTART_NOT_FULL_VIRTUAL_REFEREE',
    restartEvidence: restarts, acceptedStoppageGroups: requested.size,
    normalSubstitutionCount, refereeOrigin: 'INTERNAL_V8_REPLAY',
    wallClockTimingAuthenticated: false,
    fullLaw8RestartProcedureVerified: false,
    result: checked.result,
  };
}
